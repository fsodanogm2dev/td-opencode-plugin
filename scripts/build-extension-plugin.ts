/**
 * Build the standalone OpenCode plugin that the OpenChamber extension ships.
 *
 *   bun scripts/build-extension-plugin.ts [--check]
 *
 * Bundles `src/index.ts` into `extension/plugin/index.js`, one ES module that default-exports `{ id, setup }`.
 * OpenChamber hands the folder to OpenCode, which imports it with nothing installed, so the bundle may import only
 * Node built-in modules. The catalog stays in `data/fuelix-models.json`; the bundle reads it from
 * `../../data/fuelix-models.json`, relative to its own URL, the same path the source uses.
 *
 * With `--check`, the script builds in memory and fails when the committed bundle is out of date.
 */

import { readFile } from "node:fs/promises"
import { builtinModules } from "node:module"
import { join, resolve } from "node:path"

const ROOT = resolve(import.meta.dir, "..")
const ENTRY = join(ROOT, "src/index.ts")
const OUT_FILE = join(ROOT, "extension/plugin/index.js")

const BUILTINS = new Set(builtinModules.flatMap((name) => [name, `node:${name}`]))

/** Returns the specifiers of the static and dynamic imports in `code` that are not Node built-in modules. */
export function externalImports(code: string): string[] {
  const found = new Set<string>()
  const patterns = [/\bfrom\s*["']([^"']+)["']/g, /\bimport\s*["']([^"']+)["']/g, /\bimport\(\s*["']([^"']+)["']\s*\)/g]
  for (const pattern of patterns) {
    for (const match of code.matchAll(pattern)) {
      const specifier = match[1]
      if (specifier !== undefined && !BUILTINS.has(specifier)) found.add(specifier)
    }
  }
  return [...found].sort()
}

export async function buildPlugin(): Promise<string> {
  const pkg = JSON.parse(await readFile(join(ROOT, "package.json"), "utf8")) as { name: string; version: string }
  const result = await Bun.build({
    entrypoints: [ENTRY],
    target: "node",
    format: "esm",
    splitting: false,
    minify: false,
    sourcemap: "none",
    packages: "bundle",
    banner: `// ${pkg.name} v${pkg.version}. Generated by scripts/build-extension-plugin.ts. Do not edit.`,
  })
  if (!result.success) {
    throw new Error(`Plugin build failed:\n${result.logs.map((log) => log.message).join("\n")}`)
  }
  const output = result.outputs[0]
  if (result.outputs.length !== 1 || output === undefined) throw new Error("Plugin build must produce one file.")
  const code = await output.text()
  const external = externalImports(code)
  if (external.length > 0) throw new Error(`Plugin bundle imports non-built-in modules: ${external.join(", ")}`)
  return code.endsWith("\n") ? code : `${code}\n`
}

async function main(): Promise<number> {
  const check = process.argv.includes("--check")
  const code = await buildPlugin()
  if (check) {
    const current = await Bun.file(OUT_FILE).text().catch(() => undefined)
    if (current !== code) {
      console.error("extension/plugin/index.js is out of date. Run `bun run plugin:build`.")
      return 1
    }
    console.log("extension/plugin/index.js is up to date.")
    return 0
  }
  await Bun.write(OUT_FILE, code)
  console.log(`Wrote ${OUT_FILE} (${code.length} bytes).`)
  return 0
}

if (import.meta.main) process.exit(await main())
